#!/usr/bin/env python3
"""Every number quoted in the text of the paper, regenerated from the released results (standard library only).

  python3 -I paper_numbers.py ../results/results-final-relabeled.csv --traces ../traces --markdown ../reports/paper-numbers.md

The tables and the figure come from analyze.py, figure_data.py and sensitivity.py. This script covers the numbers
that appear only in the running text, section by section, and states the population behind each one. No API calls.
"""

from __future__ import annotations

import argparse
import glob
import gzip
import json
import math
import os
import re
import sys
from collections import Counter, defaultdict

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))

from analyze import _i, load, relative_risk, wilson  # noqa: E402
from detector import answer_is_correct, decimals_in, final_mention_from_text  # noqa: E402

TIERS = (("small", "claude-haiku-5-5"), ("mid", "claude-sonnet-5-5"), ("large", "claude-opus-5-5"))
P3 = ("NEUTRAL", "BREVITY", "FAILURE")


def pc(k: float, n: float) -> str:
    return "n/a" if not n else f"{100 * k / n:.1f}"


def mcnemar_p(b: int, c: int) -> float:
    m = b + c
    if m == 0:
        return 1.0
    return min(1.0, 2 * sum(math.comb(m, k) for k in range(0, min(b, c) + 1)) / 2 ** m)


def fp(p: float) -> str:
    return "<0.001" if p < 0.001 else f"{p:.3f}"


def wrong(rs: list[dict]) -> int:
    return sum(1 for r in rs if _i(r, "correct") == 0)


def base(item_id: str) -> str:
    """Counterfactual rows carry the original item id plus ':cf'."""
    return item_id[:-3] if item_id.endswith(":cf") else item_id


def index(rows: list[dict], **kw) -> dict[str, dict]:
    return {base(r["item_id"]): r for r in rows if all(r[k] == v for k, v in kw.items())}


def paired(a: dict[str, dict], b: dict[str, dict], metric: str) -> tuple[int, int, int]:
    """(only in a, only in b, shared items) for a 0/1 metric on items present in both."""
    x = y = n = 0
    for item, ra in a.items():
        rb = b.get(item)
        if rb is None:
            continue
        n += 1
        va, vb = _i(ra, metric), _i(rb, metric)
        x += va == 1 and vb == 0
        y += va == 0 and vb == 1
    return x, y, n


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("csv")
    ap.add_argument("--markdown", default=None)
    ap.add_argument("--boot", type=int, default=1000)
    ap.add_argument("--traces", default=None, help="traces folder; adds the count of calls that refer to a tainted result by id")
    args = ap.parse_args()
    rows = load(args.csv)
    for r in rows:
        r["tier"] = {m: t for t, m in TIERS}.get(r["model"], r["model"])
    orig = [r for r in rows if _i(r, "counterfactual") == 0 and r["pressure"] != "PERTURB"]
    cf = [r for r in rows if _i(r, "counterfactual") == 1]
    probe = [r for r in rows if r["pressure"] == "PERTURB"]
    s0 = [r for r in orig if r["seed"] == "0"]
    out: list[str] = [f"# Numbers in the text of the paper ({len(rows)} episodes: {len(orig)} grid, {len(probe)} probe, {len(cf)} counterfactual)", "",
                      "Generated by `harness/paper_numbers.py` from `results/results-final-relabeled.csv`. Tables and the figure come from `analyze.py`, `figure_data.py` and `sensitivity.py`; this file covers the numbers quoted in the running text. Seed 0 is the first replicate; only small-tier REQUIRED x NEUTRAL has seeds 1 and 2.", ""]
    add = out.append

    # ---------------- 6.1
    add("## 6.1 How often lineage breaks by default (OPTIONAL, original items)")
    for t, m in TIERS:
        g = [r for r in orig if r["model"] == m and r["regime"] == "OPTIONAL" and r["pressure"] == "NEUTRAL"]
        k = sum(_i(r, "leaked_strict") for r in g)
        p, lo, hi = wilson(k, len(g))
        add(f"- {t} NEUTRAL: strict leak {k}/{len(g)} = {100*p:.1f}% (Wilson {100*lo:.1f} to {100*hi:.1f}); bypass {pc(sum(_i(r,'tool_bypass') for r in g), len(g))}%; loose {pc(sum(_i(r,'leaked_loose') for r in g), len(g))}%")
    for (ta, ma), (tb, mb) in ((TIERS[0], TIERS[1]), (TIERS[1], TIERS[2])):
        a = index(s0, model=ma, regime="OPTIONAL", pressure="NEUTRAL")
        b = index(s0, model=mb, regime="OPTIONAL", pressure="NEUTRAL")
        x, y, n = paired(a, b, "leaked_strict")
        add(f"- {ta} vs {tb} at NEUTRAL, same items: leaked only on {ta} {x}, only on {tb} {y} (n {n}), McNemar p {fp(mcnemar_p(x, y))}")
    for p in ("NEUTRAL", "BREVITY", "FAILURE", "BREVITY_CTRL"):
        g = [r for r in orig if r["regime"] == "OPTIONAL" and r["pressure"] == p]
        tot = sum(_i(r, f"L{k}_final") for r in g for k in (1, 2, 3, 4))
        add(f"- sub-type shares of strict leaks, OPTIONAL {p}, pooled over tiers: " + ", ".join(f"L{k} {pc(sum(_i(r, f'L{k}_final') for r in g), tot)}%" for k in (1, 2, 3, 4)))
    add("")

    # ---------------- 6.2
    add("## 6.2 After one tool error (FAILURE)")
    for reg in ("OPTIONAL", "REQUIRED", "GATE"):
        for t, m in TIERS:
            g = [r for r in orig if r["model"] == m and r["regime"] == reg and r["pressure"] == "FAILURE"]
            if not g:
                continue
            n = len(g)
            add(f"- {reg} {t} (n {n}): reported {pc(sum(_i(r,'reported_failure') for r in g), n)}%, retried (2+ calls) {pc(sum(1 for r in g if _i(r,'n_tool_calls') >= 2), n)}%, strict leak {pc(sum(_i(r,'leaked_strict') for r in g), n)}%, accuracy {pc(n - wrong(g), n)}%")
    add("- Episodes that hit the error (OPTIONAL FAILURE, at least one calculator call; the first call is the one that fails):")
    for t, m in TIERS:
        g = [r for r in orig if r["model"] == m and r["regime"] == "OPTIONAL" and r["pressure"] == "FAILURE"]
        h = [r for r in g if _i(r, "n_tool_calls") >= 1]
        add(f"  - {t}: no call {len(g) - len(h)}/{len(g)} ({pc(len(g) - len(h), len(g))}%); among the {len(h)} that hit the error: retried {pc(sum(1 for r in h if _i(r,'n_tool_calls') >= 2), len(h))}%, strict leak {pc(sum(_i(r,'leaked_strict') for r in h), len(h))}%")
    for t, m in TIERS:
        a = index(s0, model=m, regime="OPTIONAL", pressure="NEUTRAL")
        b = index(s0, model=m, regime="OPTIONAL", pressure="FAILURE")
        x, y, n = paired(a, b, "leaked_strict")
        add(f"- {t} NEUTRAL vs FAILURE (OPTIONAL): leaked at NEUTRAL only {x}, under FAILURE only {y}, p {fp(mcnemar_p(x, y))}")
    for (ta, ma), (tb, mb) in ((TIERS[0], TIERS[1]), (TIERS[1], TIERS[2])):
        a = index(s0, model=ma, regime="OPTIONAL", pressure="FAILURE")
        b = index(s0, model=mb, regime="OPTIONAL", pressure="FAILURE")
        x, y, n = paired(a, b, "leaked_strict")
        add(f"- {ta} vs {tb} under FAILURE, same items: leaked only on {ta} {x}, only on {tb} {y}, p {fp(mcnemar_p(x, y))}")
    a = index(s0, model=TIERS[1][1], regime="OPTIONAL", pressure="NEUTRAL")
    b = index(s0, model=TIERS[1][1], regime="OPTIONAL", pressure="BREVITY")
    x, y, n = paired(a, b, "leaked_strict")
    add(f"- mid NEUTRAL vs BREVITY: leaked at NEUTRAL only {x}, under BREVITY only {y}, p {fp(mcnemar_p(x, y))}")
    add("")

    # ---------------- 6.3
    add("## 6.3 BREVITY against BREVITY-CTRL (OPTIONAL)")
    for t, m in (TIERS[0], TIERS[2]):
        a = index(s0, model=m, regime="OPTIONAL", pressure="BREVITY")
        b = index(s0, model=m, regime="OPTIONAL", pressure="BREVITY_CTRL")
        x, y, n = paired(a, b, "leaked_strict")
        ga, gb = list(a.values()), list(b.values())
        add(f"- {t}: BREVITY {pc(sum(_i(r,'leaked_strict') for r in ga), len(ga))}% vs CTRL {pc(sum(_i(r,'leaked_strict') for r in gb), len(gb))}%; leaked under BREVITY only {x}, under CTRL only {y}, p {fp(mcnemar_p(x, y))}; bypass {pc(sum(_i(r,'tool_bypass') for r in ga), len(ga))}% vs {pc(sum(_i(r,'tool_bypass') for r in gb), len(gb))}%")
    add("")

    # ---------------- 6.4
    add("## 6.4 REQUIRED (prompt-time verification)")
    for t, m in TIERS:
        o = [r for r in s0 if r["model"] == m and r["regime"] == "OPTIONAL" and r["pressure"] in P3]
        q = [r for r in s0 if r["model"] == m and r["regime"] == "REQUIRED" and r["pressure"] in P3]
        add(f"- {t} accuracy, NEUTRAL+BREVITY+FAILURE, seed 0: OPTIONAL {pc(len(o) - wrong(o), len(o))}% vs REQUIRED {pc(len(q) - wrong(q), len(q))}%")
    ps = []
    for t, m in TIERS:
        for p in P3:
            a = index(s0, model=m, regime="OPTIONAL", pressure=p)
            b = index(s0, model=m, regime="REQUIRED", pressure=p)
            x, y, n = paired(a, b, "correct")
            if n:
                ga, gb = [a[i] for i in a if i in b], [b[i] for i in a if i in b]
                pv = mcnemar_p(x, y)
                ps.append(pv)
                add(f"- accuracy {t} {p}, OPTIONAL vs REQUIRED on {n} shared items: {pc(n - wrong(ga), n)} vs {pc(n - wrong(gb), n)}; correct only under OPTIONAL {x}, only under REQUIRED {y}; p {fp(pv)}; Holm-adjusted over these nine: see below")
    srt = sorted(ps)
    holm = [min(1.0, max((len(srt) - j) * srt[j] for j in range(i + 1))) for i in range(len(srt))]
    add(f"- the nine accuracy p values sorted: {', '.join(fp(p) for p in srt)}; Holm-adjusted: {', '.join(fp(p) for p in holm)}")
    for t, m in TIERS:
        g = [r for r in orig if r["model"] == m and r["regime"] == "REQUIRED"]
        cells = defaultdict(list)
        for r in g:
            cells[r["pressure"]].append(r)
        add(f"- {t} REQUIRED argument leakage by pressure: " + ", ".join(f"{p} {pc(sum(_i(r,'argument_leakage') for r in v), len(v))}%" for p, v in sorted(cells.items())))
    rq = [r for r in orig if r["regime"] == "REQUIRED" and _i(r, "leaked_strict") == 1]
    items = Counter(r["item_id"] for r in rq)
    add(f"- REQUIRED strict leaks on the original items (all tiers, pressures, seeds): {len(rq)}; laundered (L4) {sum(1 for r in rq if _i(r,'L4_final'))}; from {len(items)} items: " + ", ".join(f"{k} x{v}" for k, v in items.most_common()))
    top = items.most_common(1)[0][0] if items else None
    add(f"- of these, on the most frequent item: {items[top] if top else 0}, laundered {sum(1 for r in rq if r['item_id'] == top and _i(r,'L4_final'))}")
    add("")

    # ---------------- 6.5
    add("## 6.5 Tool-perturbation probe (REQUIRED, first calculator result returned 3 percent too high)")
    for t, m in (TIERS[0], TIERS[2]):
        g = [r for r in probe if r["model"] == m and _i(r, "perturbed") == 1]
        n = len(g)
        allp = [r for r in probe if r["model"] == m]
        fol = [r for r in g if _i(r, "followed_tool")]
        folc = [r for r in fol if _i(r, "correct")]

        def eqp(r: dict) -> int:
            try:
                pred = float(r["pred"])
                ptv = float(r["perturbed_true_value"]) * 1.03
            except ValueError:
                return 0
            fm = final_mention_from_text(r["final_text"])
            return int(answer_is_correct(pred, ptv, pred_decimals=decimals_in(fm.raw) if fm else None))

        hid = [r for r in g if _i(r, "hidden_computation")]
        hf = [r for r in hid if _i(r, "leaked_strict")]
        add(f"- {t}: {len(allp)} probe episodes, {n} with a perturbed result; answer = last result {len(fol)} ({pc(len(fol), n)}%), of which correct {len(folc)} ({sum(1 for r in folc if _i(r,'n_tool_calls') > 1)} after more than one call)")
        add(f"  - wrong and = last result {sum(1 for r in fol if not _i(r,'correct'))} ({pc(sum(1 for r in fol if not _i(r,'correct')), n)}%); wrong and = perturbed value {sum(1 for r in g if eqp(r) and not _i(r,'correct'))} ({pc(sum(1 for r in g if eqp(r) and not _i(r,'correct')), n)}%)")
        add(f"  - accuracy {pc(n - wrong(g), n)}%; discrepancy mentioned {pc(sum(_i(r,'reported_discrepancy') for r in g), n)}%; hidden computation {len(hid)} ({pc(len(hid), n)}%), flagged {len(hf)} (L2 {sum(1 for r in hf if _i(r,'L2_final'))}), unflagged {len(hid) - len(hf)} ({pc(len(hid) - len(hf), n)}%)")
        add(f"  - answers equal to the last result flagged: {sum(1 for r in fol if _i(r,'leaked_strict'))} of {len(fol)}")
        un = Counter()
        for r in hid:
            if _i(r, "leaked_strict"):
                continue
            try:
                ms = json.loads(r["mentions"])
            except ValueError:
                ms = []
            un["/".join(m.get("label", "?") for m in ms if m.get("where") == "final") or "no answer mention"] += 1
        add("  - unflagged hidden computations by answer-line label: " + ", ".join(f"{k} {v}" for k, v in un.most_common()) + " (TOOL_OUT: equals an earlier clean calculator result; COPY_CTX: equals a context number)")
    add("")

    # ---------------- 6.6
    add("## 6.6 Does an untraceable number predict a wrong one?")
    for name, pool in (("original, OPTIONAL+REQUIRED+GATE", [r for r in orig if r["regime"] in ("OPTIONAL", "REQUIRED", "GATE")]),
                       ("original, OPTIONAL+REQUIRED (Table 6 rows)", [r for r in orig if r["regime"] in ("OPTIONAL", "REQUIRED")]),
                       ("counterfactual, OPTIONAL+REQUIRED", cf)):
        le = [r for r in pool if _i(r, "leaked_strict")]
        tr = [r for r in pool if not _i(r, "leaked_strict")]
        rr = (wrong(le) / len(le)) / (wrong(tr) / len(tr))
        add(f"- crude, {name}: leaked wrong {wrong(le)}/{len(le)} ({pc(wrong(le), len(le))}%), traceable wrong {wrong(tr)}/{len(tr)} ({pc(wrong(tr), len(tr))}%), RR {rr:.2f}")
    for t, m in (TIERS[0], TIERS[2]):
        g = [r for r in cf if r["model"] == m and r["regime"] == "OPTIONAL"]
        le = [r for r in g if _i(r, "leaked_strict")]
        tr = [r for r in g if not _i(r, "leaked_strict")]
        add(f"- counterfactual OPTIONAL {t}: leak {pc(len(le), len(g))}%, leaked wrong {pc(wrong(le), len(le))}%, traceable wrong {pc(wrong(tr), len(tr))}%")
        cfi = {base(r["item_id"]) for r in cf}
        ob = [r for r in s0 if r["model"] == m and r["regime"] == "OPTIONAL" and r["pressure"] in P3]
        obm = [r for r in ob if r["item_id"] in cfi]
        x = y = 0
        for p in P3:
            a = index(obm, pressure=p)
            b = index(g, pressure=p)
            dx, dy, _ = paired(a, b, "leaked_strict")
            x += dx
            y += dy
        add(f"  - same {len(cfi)} items in original form, same three pressures: leak {pc(sum(_i(r,'leaked_strict') for r in obm), len(obm))}%; leaked only in original {x}, only counterfactual {y}, p {fp(mcnemar_p(x, y))}")
        add(f"  - tool calls per episode counterfactual {sum(_i(r,'n_tool_calls') for r in g)/len(g):.2f} vs original (all 300 items, same pressures) {sum(_i(r,'n_tool_calls') for r in ob)/len(ob):.2f}; accuracy {pc(len(g)-wrong(g), len(g))}% vs {pc(len(ob)-wrong(ob), len(ob))}%")
    for arm in ("original", "counterfactual"):
        for byp in (False, True):
            add("- " + relative_risk(rows, n_boot=args.boot, arm=arm, bypass_stratum=byp)[1])
    ob = [r for r in orig if r["regime"] == "OPTIONAL" and _i(r, "tool_bypass")]
    add(f"- OPTIONAL bypass episodes on the original items that leak (strict): {sum(_i(r,'leaked_strict') for r in ob)}/{len(ob)} ({pc(sum(_i(r,'leaked_strict') for r in ob), len(ob))}%)")
    add("- OPTIONAL, by tool use (bypass = no call although the gold program needs arithmetic):")
    for arm, pool in (("original", orig), ("counterfactual", cf)):
        for byp in (0, 1):
            g = [r for r in pool if r["regime"] == "OPTIONAL" and _i(r, "tool_bypass") == byp]
            le = [r for r in g if _i(r, "leaked_strict")]
            tr = [r for r in g if not _i(r, "leaked_strict")]
            add(f"  - {arm}, {'bypass' if byp else 'tool used or not needed'}: leaked wrong {wrong(le)}/{len(le)} ({pc(wrong(le), len(le))}%), traceable wrong {wrong(tr)}/{len(tr)} ({pc(wrong(tr), len(tr))}%), RR {(wrong(le)/len(le))/(wrong(tr)/len(tr)):.2f}")
    bt = [r for r in cf if r["regime"] == "OPTIONAL" and _i(r, "tool_bypass") and not _i(r, "leaked_strict")]
    lab = Counter()
    for r in bt:
        try:
            ms = json.loads(r["mentions"])
        except ValueError:
            ms = []
        lab["/".join(m.get("label", "?") for m in ms if m.get("where") == "final") or "none"] += 1
    add(f"  - counterfactual bypass episodes with a traceable answer: {len(bt)}, answer-line label " + ", ".join(f"{k} {v}" for k, v in lab.most_common()) + f"; wrong {wrong(bt)}")
    rq = [r for r in orig + cf if r["regime"] == "REQUIRED" and _i(r, "leaked_strict")]
    rt = [r for r in orig + cf if r["regime"] == "REQUIRED" and not _i(r, "leaked_strict")]
    items = Counter(r["item_id"] for r in rq)
    witems = Counter(r["item_id"] for r in rq if not _i(r, "correct"))
    add(f"- REQUIRED strict leaks, original + counterfactual: wrong {wrong(rq)}/{len(rq)} ({pc(wrong(rq), len(rq))}%), traceable wrong {pc(wrong(rt), len(rt))}%; mid tier {wrong([r for r in rq if r['tier']=='mid'])}/{sum(1 for r in rq if r['tier']=='mid')}; from {len(items)} items")
    bw = Counter(base(r["item_id"]) for r in rq if not _i(r, "correct"))
    two = [k for k, _ in bw.most_common(2)]
    rest = [r for r in rq if base(r["item_id"]) not in two]
    add(f"  - wrong leaks by item: " + ", ".join(f"{k} x{v}" for k, v in witems.most_common()) + f"; without the two most frequent base items ({', '.join(two)}, original and counterfactual): wrong {wrong(rest)}/{len(rest)}")
    add(f"  - wrong leaks on those two base items: {wrong(rq) - wrong(rest)} of {wrong(rq)}")
    k3 = [r for r in orig if r["regime"] == "OPTIONAL" and r["k_bucket"] == "3+"]
    le = [r for r in k3 if _i(r, "leaked_strict")]
    tr = [r for r in k3 if not _i(r, "leaked_strict")]
    add(f"- OPTIONAL originals, K 3+: leaked correct {pc(len(le)-wrong(le), len(le))}% vs traceable correct {pc(len(tr)-wrong(tr), len(tr))}%")
    add("")

    # ---------------- 3 / 5 scoring
    add("## Scoring: wrong answers that differ from the gold only in sign or by a factor of 1,000 or 1,000,000 (grid and arms, probe excluded)")
    gp = orig + cf
    wr = [r for r in gp if not _i(r, "correct")]

    def kind(r: dict) -> str:
        try:
            p, g = float(r["pred"]), float(r["gold"])
        except ValueError:
            return ""
        if not p or not g:
            return ""
        q = abs(p / g)
        for f in (1e3, 1e6, 1e-3, 1e-6):
            if abs(q / f - 1) < 0.006:
                return "unit"
        if p * g < 0 and answer_is_correct(-p, g):
            return "sign"
        return ""

    kc = Counter(kind(r) for r in wr)
    add(f"- wrong answers {len(wr)}; sign only {kc['sign']}; thousand/million factor {kc['unit']}")
    for arm, pool in (("original", orig), ("counterfactual", cf)):
        g = [r for r in pool if r["regime"] == "OPTIONAL"]
        for lk in (1, 0):
            x = [r for r in g if _i(r, "leaked_strict") == lk]
            w = [r for r in x if not _i(r, "correct")]
            add(f"  - OPTIONAL {arm}, {'leaked' if lk else 'traceable'}: wrong {pc(len(w), len(x))}%, counting sign and unit re-expressions as correct {pc(len(w) - sum(1 for r in w if kind(r)), len(x))}%")
    add("")

    # ---------------- 6.7
    add("## 6.7 The gate")
    G = [r for r in orig if r["regime"] == "GATE" and _i(r, "gate_rejections") > 0]
    R = {(r["model"], r["pressure"], r["item_id"]): r for r in s0 if r["regime"] == "REQUIRED"}
    more = same = fewer = 0
    for r in G:
        q = R.get((r["model"], r["pressure"], r["item_id"]))
        if q is None:
            continue
        a, b = _i(r, "n_tool_calls"), _i(q, "n_tool_calls")
        more += a > b
        same += a == b
        fewer += a < b
    add(f"- GATE episodes with a rejection: {len(G)}; prose only (answer line traceable) {sum(1 for r in G if _i(r,'rejected_strict_clean_n') > 0)}; vs REQUIRED seed 0 on the same item and pressure: more calls {more}, as many {same}, fewer {fewer}")
    gl = [r for r in orig if r["regime"] == "GATE" and _i(r, "leaked_strict")]
    add(f"- GATE strict leaks: {len(gl)} (" + ", ".join(f"{r['tier']} {r['pressure']} {r['item_id']}" for r in gl) + ")")
    add("")

    # ---------------- 7
    add("## 7 Reproducibility")
    n = [r for r in orig if r["model"] == TIERS[0][1] and r["regime"] == "REQUIRED" and r["pressure"] == "NEUTRAL"]
    by = defaultdict(list)
    for r in n:
        by[r["seed"]].append(r)
    add("- noise floor, small REQUIRED NEUTRAL: " + "; ".join(f"seed {s} n {len(v)} strict {pc(sum(_i(r,'leaked_strict') for r in v), len(v))}% (leaking items: {', '.join(sorted({r['item_id'] for r in v if _i(r,'leaked_strict')}))})" for s, v in sorted(by.items())))
    add(f"- replay_diverged: {sum(1 for r in rows if _i(r, 'replay_diverged'))}")
    if args.traces:
        from detector import DetectorConfig, extract_numbers, matches_any
        cfg = DetectorConfig()
        calls = ref = ref_t = 0
        eps = set()
        for f in sorted(glob.glob(os.path.join(args.traces, "*.jsonl*"))):
            if "pilot" in os.path.basename(f):
                continue
            with (gzip.open(f, "rt") if f.endswith(".gz") else open(f)) as fh:
                for line in fh:
                    d = json.loads(line)
                    u = d["messages"][0]["content"]
                    ctx = extract_numbers(u if isinstance(u, str) else json.dumps(u))
                    outs: list[float] = []
                    status: dict[str, str] = {}
                    for i, c in enumerate(d["tool_calls"]):
                        calls += 1
                        clean = all(any(abs(abs(a) - k) < 1e-9 for k in cfg.constant_args) or matches_any([a, -a], ctx, cfg) or matches_any([a, -a], outs, cfg, tool_refs=True) for a in c["arg_numbers"])
                        ids = re.findall(r"\br(\d+)\b", c.get("expression") or "")
                        if ids:
                            ref += 1
                            if any(status.get(f"r{x}") == "T" for x in ids):
                                ref_t += 1
                                eps.add((d["item_id"], d["cond"], d["seed"], d["model"]))
                        if c["output_value"] is None or c["error"]:
                            status[f"r{i + 1}"] = "E"
                            continue
                        status[f"r{i + 1}"] = "C" if clean else "T"
                        if clean:
                            outs.append(c["output_value"])
        add(f"- result ids (context numbers taken from the user message): {calls} calculator calls, {ref} refer to an earlier result by id, {ref_t} of them to a tainted result, in {len(eps)} episodes: " + "; ".join(" ".join(map(str, e)) for e in sorted(eps)))
    text = "\n".join(out)
    print(text)
    if args.markdown:
        with open(args.markdown, "w") as fh:
            fh.write(text + "\n")
    return 0


